describe("OpenAPI", () => {
  it("documents every API route", () => {
    const paths = openApi.paths as Record<string, Record<string, unknown>>;
    for (const [method, path] of required) {
      expect(paths[path]?.[method], `${method} ${path}`).toBeTruthy();
    }
    expect(Object.values(paths).reduce((count, item) => count + Object.keys(item).length, 0)).toBe(required.length);
  });
});
